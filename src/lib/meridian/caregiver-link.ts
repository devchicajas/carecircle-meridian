/**
 * Ensure the signed-in Family Caregiver has a Meridian caregiver that still exists.
 * Stale CG-001/CG-002 mappings after UUID migration cause invite redemption failures.
 */
import { updateUserProfile } from "@/lib/auth/db";
import { MERIDIAN_OBJECTS } from "@/lib/meridian/objects";
import {
  flattenRecord,
  recordEnvelopeId,
} from "@/lib/meridian/records";
import {
  createPlatformSDKFromEnv,
  PlatformSDKError,
} from "@/lib/sdk/platformSDK";
import { pickString } from "@/lib/utils";

export async function ensureLiveCaregiverProfile(input: {
  userId: string;
  email: string;
  firstName: string;
  lastName: string;
  preferredLanguage?: "English" | "Spanish";
  meridianCaregiverId?: string;
  meridianCaregiverBusinessId?: string;
}) {
  const sdk = createPlatformSDKFromEnv();
  if (!sdk) {
    throw new PlatformSDKError({
      status: 503,
      code: "MISSING_API_KEY",
      detail: "Unable to reach Meridian right now.",
    });
  }

  const { records } = await sdk.listRecords(MERIDIAN_OBJECTS.caregiver, {
    limit: 200,
  });

  const byId = (records as Record<string, unknown>[]).find((row) => {
    const flat = flattenRecord(row);
    const id = recordEnvelopeId(row);
    const bid = pickString(flat, ["caregiverId"]);
    return (
      id === input.meridianCaregiverId ||
      bid === input.meridianCaregiverBusinessId ||
      id === input.meridianCaregiverBusinessId ||
      bid === input.meridianCaregiverId
    );
  });

  if (byId) {
    const flat = flattenRecord(byId);
    return {
      id: recordEnvelopeId(byId),
      businessId: pickString(flat, ["caregiverId"]),
      reused: true as const,
    };
  }

  // Prefer exact email Family Caregiver row if present.
  const byEmail = (records as Record<string, unknown>[]).find((row) => {
    const flat = flattenRecord(row);
    const email = pickString(flat, ["emailAddress", "email"]);
    return (
      !!email && email.toLowerCase() === input.email.toLowerCase()
    );
  });

  if (byEmail) {
    const id = recordEnvelopeId(byEmail);
    await sdk.updateRecord(
      MERIDIAN_OBJECTS.caregiver,
      id,
      {
        firstName: input.firstName,
        lastName: input.lastName,
        emailAddress: input.email,
        caregiverType: "Family Caregiver",
        status: "Active",
        preferredLanguage: input.preferredLanguage || "English",
        portalAccessStatus: "Linked",
      },
      `CareCircle: re-link caregiver profile for ${input.email}`,
    );
    const { records: again } = await sdk.listRecords(MERIDIAN_OBJECTS.caregiver, {
      limit: 200,
    });
    const saved = (again as Record<string, unknown>[]).find(
      (r) => recordEnvelopeId(r) === id,
    );
    const flat = flattenRecord(saved || byEmail);
    const linked = {
      id,
      businessId: pickString(flat, ["caregiverId"]),
      reused: true as const,
    };
    updateUserProfile(input.userId, {
      meridianCaregiverId: linked.id,
      meridianCaregiverBusinessId: linked.businessId || null,
      onboarded: true,
    });
    return linked;
  }

  // Create a new Family Caregiver (UUID business id generated by Meridian).
  const created = await sdk.createRecord(
    MERIDIAN_OBJECTS.caregiver,
    {
      firstName: input.firstName,
      lastName: input.lastName,
      emailAddress: input.email,
      caregiverType: "Family Caregiver",
      status: "Active",
      preferredLanguage: input.preferredLanguage || "English",
      portalAccessStatus: "Linked",
    },
    `CareCircle: create caregiver profile for invite redeem (${input.email})`,
  );
  const id = recordEnvelopeId(created as Record<string, unknown>);
  const { records: again } = await sdk.listRecords(MERIDIAN_OBJECTS.caregiver, {
    limit: 200,
  });
  const saved = (again as Record<string, unknown>[]).find(
    (r) => recordEnvelopeId(r) === id,
  );
  if (!saved) {
    throw new PlatformSDKError({
      status: 502,
      code: "READBACK_FAILED",
      detail: "Caregiver profile could not be confirmed after create.",
    });
  }
  const flat = flattenRecord(saved);
  const linked = {
    id,
    businessId: pickString(flat, ["caregiverId"]),
    reused: false as const,
  };
  updateUserProfile(input.userId, {
    meridianCaregiverId: linked.id,
    meridianCaregiverBusinessId: linked.businessId || null,
    onboarded: true,
  });
  return linked;
}
